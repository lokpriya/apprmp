    public function run(): void
    {
        $rows = [];
        $now  = now();

        foreach ($this->defaults() as $category => $options) {
            foreach ($options as $i => $opt) {
                $rows[] = [
                    'category'            => $category,
                    'value'               => $opt[0],
                    'label_ne'            => $opt[1],
                    'label_en'            => $opt[2] ?? null,
                    'sort_order'          => $i + 1,
                    'is_active'           => true,
                    'local_government_id' => null,
                    'created_at'          => $now,
                    'updated_at'          => $now,
                ];
            }
        }

        // Upsert: insert or update on category+value+null LG_id
        foreach ($rows as $row) {
            DB::table('survey_options')->updateOrInsert(
                ['category' => $row['category'], 'value' => $row['value'], 'local_government_id' => null],
                $row
            );
        }

        $this->command->info('SurveyOptionSeeder: ' . count($rows) . ' options seeded.');
    }

